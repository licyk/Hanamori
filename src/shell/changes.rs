//! Render fully calculated changes, without interpolating user data as shell code.

use crate::shell::quote::{posix_literal, powershell_literal};
use crate::shell::session::{Changes, PreparedEnvironment};
use crate::shell::syntax::Shell;
use anyhow::{ensure, Context, Result};
use std::ffi::OsStr;

/// Activation must also be restorable in the selected shell, even when an original
/// value is not used in the active environment (for example the previous compiler).
pub fn activation(prepared: &PreparedEnvironment, shell: Shell) -> Result<String> {
    let restoration = prepared.session.restoration();
    render(&restoration, shell)?;
    let mut script = render(&prepared.changes, shell)?;
    if shell == Shell::PowerShell && restoration.values().flatten().any(|value| value.is_empty()) {
        script.insert_str(0, "if ($PSVersionTable.PSVersion -lt [version]'7.5') { throw 'Hanamori: this baseline contains empty variables that require PowerShell 7.5 or newer; no changes applied' }\n");
    }
    Ok(script)
}

fn convert_posix_path(key: &str, value: &OsStr) -> bool {
    cfg!(windows)
        && !value.is_empty()
        && (key == "PATH"
            || (matches!(key, "CC" | "CXX") && std::path::Path::new(value).is_absolute()))
}

pub fn render(changes: &Changes, shell: Shell) -> Result<String> {
    if changes.is_empty() {
        return Ok(match shell {
            Shell::Cmd => "@rem No active Hanamori environment.\r\n@exit /b 0\r\n",
            _ => "# No active Hanamori environment.\n",
        }
        .into());
    }
    for key in changes.keys() {
        ensure!(
            key.bytes().enumerate().all(|(i, c)| c == b'_'
                || c.is_ascii_alphabetic()
                || (i > 0 && c.is_ascii_digit()))
                && !key.is_empty(),
            "invalid environment variable name"
        );
    }
    match shell {
        Shell::Bash | Shell::Zsh => posix(changes, shell),
        Shell::PowerShell => powershell(changes),
        Shell::Cmd => cmd(changes, None),
    }
}

fn posix(changes: &Changes, shell: Shell) -> Result<String> {
    let mut text = String::from("# Generated by Hanamori; apply in the same session that generated this snapshot.\n_hanamori_apply_environment() {\n    builtin unset -f _hanamori_apply_environment\n");
    for key in changes.keys() {
        let readonly = match shell {
            Shell::Bash => format!(
                "[[ $(builtin declare -p {key} 2>/dev/null) =~ ^declare\\ -[^[:space:]]*r ]]"
            ),
            Shell::Zsh => format!("[[ ${{(t){key}-}} == *readonly* ]]"),
            _ => unreachable!(),
        };
        text.push_str(&format!("    if {readonly}; then builtin printf '%s\\n' 'Hanamori: {key} is readonly; no changes applied' >&2; return 1; fi\n"));
    }
    // Native Windows children see Windows PATH spelling. Use the target MSYS runtime
    // instead of guessing drive mappings; conversion must finish before any assignments.
    if cfg!(windows) {
        for key in ["PATH", "CC", "CXX"] {
            if let Some(Some(value)) = changes.get(key) {
                if !convert_posix_path(key, value) {
                    continue;
                }
                let quoted = posix_literal(value)?;
                let option = if key == "PATH" { "-up" } else { "-u" };
                text.push_str(&format!("    builtin local _hanamori_{key}\n    _hanamori_{key}=$(command cygpath {option} -- {quoted}) || return $?\n"));
            }
        }
    }
    for (key, value) in changes {
        match value {
            None => text.push_str(&format!("    builtin unset {key}\n")),
            Some(value) if convert_posix_path(key, value) => {
                text.push_str(&format!("    builtin export {key}=\"$_hanamori_{key}\"\n"));
            }
            Some(value) => text.push_str(&format!(
                "    builtin export {key}={}\n",
                posix_literal(value)?
            )),
        }
    }
    text.push_str("    return 0\n}\n_hanamori_apply_environment\n");
    Ok(text)
}

fn powershell_value(value: &OsStr) -> Result<String> {
    if let Some(text) = value.to_str() {
        ensure!(
            !text.contains('\0'),
            "PowerShell value contains a NUL character"
        );
        return Ok(powershell_literal(text));
    }
    #[cfg(windows)]
    {
        use std::os::windows::ffi::OsStrExt;
        let wide: Vec<_> = value.encode_wide().collect();
        ensure!(
            !wide.contains(&0),
            "PowerShell value contains a NUL character"
        );
        Ok(format!(
            "(-join [char[]]@({}))",
            wide.iter()
                .map(u16::to_string)
                .collect::<Vec<_>>()
                .join(",")
        ))
    }
    #[cfg(unix)]
    {
        anyhow::bail!(
            "PowerShell cannot represent a non-Unicode native value; use Bash/Zsh for restoration"
        )
    }
}

fn powershell(changes: &Changes) -> Result<String> {
    let mut text = String::from(
        "# Generated by Hanamori; dot-source in the session that generated this snapshot.\n& {\n",
    );
    if changes.values().flatten().any(|value| value.is_empty()) {
        text.push_str("    if ($PSVersionTable.PSVersion -lt [version]'7.5') { throw 'Hanamori: restoring an empty variable requires PowerShell 7.5 or newer; no changes applied' }\n");
    }
    text.push_str("    $_hanamori_changes = @{\n");
    for (key, value) in changes {
        let value = value
            .as_ref()
            .map(|value| powershell_value(value))
            .transpose()?
            .unwrap_or_else(|| "$null".into());
        text.push_str(&format!("        {} = {value}\n", powershell_literal(key)));
    }
    text.push_str("    }\n    $_hanamori_before = @{}\n    foreach ($_hanamori_key in $_hanamori_changes.Keys) {\n        $_hanamori_before[$_hanamori_key] = [Environment]::GetEnvironmentVariable($_hanamori_key, 'Process')\n    }\n    try {\n        foreach ($_hanamori_key in $_hanamori_changes.Keys) {\n            [Environment]::SetEnvironmentVariable($_hanamori_key, $(if ($null -eq $_hanamori_changes[$_hanamori_key]) { [NullString]::Value } else { $_hanamori_changes[$_hanamori_key] }), 'Process')\n        }\n    } catch {\n        foreach ($_hanamori_key in $_hanamori_before.Keys) {\n            [Environment]::SetEnvironmentVariable($_hanamori_key, $(if ($null -eq $_hanamori_before[$_hanamori_key]) { [NullString]::Value } else { $_hanamori_before[$_hanamori_key] }), 'Process')\n        }\n        throw 'Hanamori: environment update failed; previous variables restored'\n    }\n}\n");
    Ok(text)
}

/// Batch entries already captured their caller's code page without spawning CMD.
/// Validate with the same renderer, then omit the subprocess-based query in that path.
pub fn cmd_at_codepage(changes: &Changes, codepage: u16) -> Result<String> {
    ensure!(codepage > 0, "CMD requires a nonzero console code page");
    render(changes, Shell::Cmd)?;
    cmd(changes, Some(codepage))
}

fn cmd(changes: &Changes, codepage: Option<u16>) -> Result<String> {
    let mut assignments = String::new();
    for (key, value) in changes {
        let value = match value {
            None => "",
            Some(value) => {
                ensure!(
                    !value.is_empty(),
                    "CMD cannot restore an empty-but-set variable; use PowerShell 7.5 or newer"
                );
                value
                    .to_str()
                    .context("CMD cannot represent a non-Unicode native value")?
            }
        };
        ensure!(
            !value.contains(['\0', '\r', '\n']),
            "CMD cannot represent multiline/NUL environment values"
        );
        let mut escaped = String::new();
        for character in value.chars() {
            match character {
                '%' => escaped.push_str("%%"),
                '^' | '"' | '&' | '|' | '<' | '>' | '(' | ')' => {
                    escaped.push('^');
                    escaped.push(character);
                }
                _ => escaped.push(character),
            }
        }
        let line = format!("@set {key}={escaped}\n");
        ensure!(
            line.encode_utf16().count() <= 8191,
            "CMD assignment for {key} exceeds its command length limit; use PowerShell or exec"
        );
        assignments.push_str(&line);
    }
    // End the FOR context before applying data: a literal %%H in a value must not
    // accidentally substitute the loop's code-page token.
    let query = match codepage {
        Some(codepage) => format!("@call :_hanamori_apply_environment {codepage}\n"),
        None => "@call :_hanamori_get_codepage\n@if errorlevel 65536 exit /b 1\n@call :_hanamori_apply_environment %errorlevel%\n".into(),
    };
    let get_codepage = if codepage.is_none() {
        ":_hanamori_get_codepage\n@for /f \"tokens=2 delims=:\" %%H in ('chcp') do @exit /b %%H\n@exit /b 65536\n"
    } else {
        ""
    };
    Ok(format!(r#"@rem Generated by Hanamori; call in the session that generated this snapshot.
@if not cmdextversion 1 (echo Hanamori: enable CMD command extensions before applying this script 1>&2 & exit /b 1)
@for /f "tokens=1 delims==" %%H in ('set ERRORLEVEL 2^>nul') do @if /i "%%H"=="ERRORLEVEL" (echo Hanamori: unset the explicit ERRORLEVEL variable before applying this script 1>&2 & exit /b 1)
@if "!"=="" (echo Hanamori: disable CMD delayed expansion before applying this script 1>&2 & exit /b 1)
{query}@exit /b %errorlevel%
{get_codepage}:_hanamori_apply_environment
@chcp 65001 >nul
@if errorlevel 1 exit /b 1
{assignments}@chcp %1 >nul
@exit /b 0
"#).replace('\n', "\r\n"))
}
