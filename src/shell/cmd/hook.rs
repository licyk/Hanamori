//! CMD batch entry. Argument interpretation and environment calculation stay in Rust.

use crate::shell::target::DirectoryTarget;
use anyhow::{ensure, Context, Result};
use std::io::Write;
use std::path::Path;

pub fn generate(
    program: &Path,
    directory: Option<&DirectoryTarget>,
    auto_activate: bool,
) -> Result<String> {
    ensure!(!auto_activate, "the CMD batch entry is invoked with a command; automatic startup activation requires persistent CMD initialization");
    ensure!(
        program.is_absolute(),
        "CMD executable path must be absolute"
    );
    let program = program
        .to_str()
        .context("CMD executable path must be Unicode")?;
    ensure!(
        !program.contains(['"', '\r', '\n', '\0']),
        "CMD executable path contains an unsupported character"
    );
    let program = program.replace('%', "%%");
    let arguments = directory
        .map(DirectoryTarget::arguments)
        .unwrap_or_default();
    let options = arguments
        .iter()
        .map(|value| {
            let value = value
                .to_str()
                .context("CMD directory arguments must be Unicode")?;
            ensure!(
                !value.contains(['"', '\r', '\n', '\0']),
                "CMD directory argument contains an unsupported character"
            );
            // Windows argv parsing consumes backslashes before a closing quote.
            let trailing = value.len() - value.trim_end_matches('\\').len();
            Ok(format!(
                "\"{}{}\"",
                value.replace('%', "%%"),
                "\\".repeat(trailing)
            ))
        })
        .collect::<Result<Vec<_>>>()?
        .join(" ");
    // No CALL around user arguments: CALL performs an extra expansion pass. Ordinary
    // commands execute in Rust with inherited streams. Successful environment changes
    // call a complete generated script after ENDLOCAL, so they affect the caller.
    let script = format!(r#"@rem Generated by Hanamori. Invoke this batch entry with use, deactivate, or an ordinary command.
@if not cmdextversion 1 (echo Hanamori: enable CMD command extensions before invoking this batch entry 1>&2 & exit /b 1)
@if "!"=="" (echo Hanamori: disable delayed expansion before invoking this batch entry 1>&2 & exit /b 1)
@for /f "tokens=1 delims==" %%H in ('set ERRORLEVEL 2^>nul') do @if /i "%%H"=="ERRORLEVEL" (echo Hanamori: unset the explicit ERRORLEVEL variable before invoking this batch entry 1>&2 & exit /b 1)
@for /f "tokens=1 delims==" %%H in ('set RANDOM 2^>nul') do @if /i "%%H"=="RANDOM" (echo Hanamori: unset the explicit RANDOM variable before invoking this batch entry 1>&2 & exit /b 1)
@setlocal DisableDelayedExpansion
@set "_HANAMORI_CMD_CP="
@set "_HANAMORI_CMD_OWNED="
@if not defined TEMP goto _hanamori_no_temp
@set "_HANAMORI_CMD_WORK=%TEMP%\hanamori-cmd-%RANDOM%-%RANDOM%-%RANDOM%"
@mkdir "%_HANAMORI_CMD_WORK%" 2>nul
@if errorlevel 1 goto _hanamori_no_temp
@set "_HANAMORI_CMD_OWNED=1"
@chcp > "%_HANAMORI_CMD_WORK%\codepage.txt"
@call :_hanamori_codepage
@if errorlevel 65536 goto _hanamori_no_temp
@set "_HANAMORI_CMD_CP=%errorlevel%"
@del /q "%_HANAMORI_CMD_WORK%\codepage.txt" >nul 2>nul
@set "_HANAMORI_CMD_RESULT=0"
@if defined _HANAMORI_CMD_PROBE goto _hanamori_finish
@chcp 65001 >nul
@if errorlevel 1 goto _hanamori_no_temp
@"{program}" shell cmd-dispatch {options} --codepage %_HANAMORI_CMD_CP% --output "%_HANAMORI_CMD_WORK%\apply.cmd" -- %*
@set "_HANAMORI_CMD_RESULT=%errorlevel%"
@chcp %_HANAMORI_CMD_CP% >nul
@if not "%_HANAMORI_CMD_RESULT%"=="0" goto _hanamori_finish
@if not exist "%_HANAMORI_CMD_WORK%\apply.cmd" goto _hanamori_finish
@endlocal & call :_hanamori_apply "%_HANAMORI_CMD_WORK%"
@exit /b %errorlevel%
:_hanamori_apply
@call "%~1\apply.cmd"
@del /q "%~1\apply.cmd" >nul 2>nul & @rd "%~1" >nul 2>nul & @if exist "%~1" echo Hanamori: temporary directory could not be removed 1>&2 & @exit /b %errorlevel%
:_hanamori_finish
@rd "%_HANAMORI_CMD_WORK%" 2>nul
@if exist "%_HANAMORI_CMD_WORK%" echo Hanamori: temporary directory retained because it is not empty or removable 1>&2
@endlocal & exit /b %_HANAMORI_CMD_RESULT%
:_hanamori_no_temp
@if not defined _HANAMORI_CMD_PROBE echo Hanamori: cannot prepare the batch entry; check TEMP and the console code page 1>&2
@if defined _HANAMORI_CMD_CP chcp %_HANAMORI_CMD_CP% >nul
@if defined _HANAMORI_CMD_OWNED del /q "%_HANAMORI_CMD_WORK%\codepage.txt" >nul 2>nul
@if defined _HANAMORI_CMD_OWNED rd "%_HANAMORI_CMD_WORK%" 2>nul
@endlocal & exit /b 1
:_hanamori_codepage
@for /f "usebackq tokens=2 delims=:" %%H in ("%_HANAMORI_CMD_WORK%\codepage.txt") do @exit /b %%H
@exit /b 65536
"#).replace('\n', "\r\n");
    ensure!(
        script
            .lines()
            .all(|line| line.encode_utf16().count() < 8191),
        "CMD entry exceeds the command length limit"
    );
    Ok(script)
}

/// The batch entry owns a fresh directory. Publish the fully rendered script without
/// overwriting any existing file and without printing script text on the command stream.
pub fn publish(output: &Path, script: &str) -> Result<()> {
    ensure!(
        output.is_absolute() && output.file_name().is_some_and(|name| name == "apply.cmd"),
        "CMD dispatch needs an absolute apply.cmd output path"
    );
    let parent = output.parent().context("CMD output has no parent")?;
    ensure!(
        parent
            .file_name()
            .and_then(|name| name.to_str())
            .is_some_and(|name| name
                .strip_prefix("hanamori-cmd-")
                .is_some_and(|suffix| !suffix.is_empty()
                    && suffix
                        .bytes()
                        .all(|byte| byte.is_ascii_alphanumeric() || byte == b'-'))),
        "CMD dispatch output must be in a fresh hanamori-cmd-* directory"
    );
    let metadata = std::fs::symlink_metadata(parent)?;
    ensure!(
        metadata.is_dir() && !crate::fs::is_link(&metadata),
        "CMD temporary directory must be an ordinary directory"
    );
    ensure!(
        std::fs::read_dir(parent)?.next().is_none(),
        "CMD temporary directory must be empty; existing files were preserved"
    );
    let mut temporary = tempfile::Builder::new()
        .prefix("hanamori-cmd-write-")
        .tempfile_in(parent)?;
    temporary.write_all(script.as_bytes())?;
    temporary.as_file().sync_all()?;
    temporary
        .persist_noclobber(output)
        .map_err(|error| error.error)
        .context("cannot publish CMD environment script")?;
    Ok(())
}
