//! Persistent CMD loader files. Publish complete immutable content before AutoRun.

use crate::locking::FileLock;
use crate::shell::target::DirectoryTarget;
use anyhow::{ensure, Context, Result};
use sha2::{Digest, Sha256};
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

/// An ASCII loader: native paths come from %~dp0, not the batch file's code page.
/// DOSKEY expands the entry variable at invocation time, without CALL's second pass
/// over the user's arguments. DOSKEY macros are for interactive prompts only.
/// Probe the entry quietly: DOSKEY and CHCP may report success without a console.
pub fn loader(auto_activate: bool, use_on_cd: bool) -> String {
    let activation = if use_on_cd {
        "@set \"_HANAMORI_CMD_CD=%~dp0cd.cmd\"\n@\"%SystemRoot%\\System32\\doskey.exe\" /exename=cmd.exe cd=\"%%_HANAMORI_CMD_CD%%\" $* >nul 2>nul\n@call \"%~dp0hanamori.cmd\" use --automatic\n"
    } else if auto_activate {
        "@if defined _HANAMORI_STATE exit /b 0\n@call \"%~dp0hanamori.cmd\" use\n@if errorlevel 1 echo Hanamori: automatic activation failed; the terminal remains usable 1>&2\n"
    } else {
        ""
    };
    format!(r#"@rem Generated by Hanamori. Persistent CMD startup loader.
@if not cmdextversion 1 (echo Hanamori: CMD initialization requires command extensions 1>&2 & exit /b 0)
@if "!"=="" (echo Hanamori: CMD initialization requires delayed expansion to be disabled 1>&2 & exit /b 0)
@for /f "tokens=1 delims==" %%H in ('set ERRORLEVEL 2^>nul') do @if /i "%%H"=="ERRORLEVEL" (echo Hanamori: unset the explicit ERRORLEVEL variable before loading CMD initialization 1>&2 & exit /b 0)
@if not exist "%~dp0hanamori.cmd" goto _hanamori_init_failed
@setlocal
@set "_HANAMORI_CMD_PROBE=1"
@call "%~dp0hanamori.cmd"
@endlocal
@if errorlevel 1 exit /b 0
@if not exist "%SystemRoot%\System32\doskey.exe" goto _hanamori_init_failed
@"%SystemRoot%\System32\doskey.exe" /exename=cmd.exe hanamori="%%_HANAMORI_CMD_ENTRY%%" $* >nul 2>nul
@if errorlevel 1 exit /b 0
@set "_HANAMORI_CMD_ENTRY=%~dp0hanamori.cmd"
@if defined _HANAMORI_CMD_CD "%SystemRoot%\System32\doskey.exe" /exename=cmd.exe cd= >nul 2>nul
@set "_HANAMORI_CMD_CD="
{activation}@exit /b 0
:_hanamori_init_failed
@echo Hanamori: cannot register the CMD entry; rerun shell init after checking the loader and DOSKEY 1>&2
@exit /b 0
"#).replace('\n', "\r\n")
}

pub struct Bundle {
    base: PathBuf,
    directory: PathBuf,
    files: Vec<(&'static str, Vec<u8>)>,
}

fn ordinary(path: &Path, directory: bool) -> Result<bool> {
    match fs::symlink_metadata(path) {
        Ok(metadata) => {
            ensure!(
                !crate::fs::is_link(&metadata)
                    && if directory {
                        metadata.is_dir()
                    } else {
                        metadata.is_file()
                    },
                "CMD initialization path has an unexpected type or link: {}",
                path.display()
            );
            Ok(true)
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(false),
        Err(error) => Err(error).with_context(|| format!("cannot inspect {}", path.display())),
    }
}

impl Bundle {
    pub fn new(
        base: &Path,
        program: &Path,
        directory: Option<&DirectoryTarget>,
        auto_activate: bool,
        use_on_cd: bool,
    ) -> Result<Self> {
        ensure!(base.is_absolute(), "CMD loader storage must be absolute");
        let mut files = vec![
            (
                "hanamori.cmd",
                crate::shell::cmd::hook::generate(program, directory, false)?.into_bytes(),
            ),
            ("init.cmd", loader(auto_activate, use_on_cd).into_bytes()),
        ];
        if use_on_cd {
            files.push((
                "cd.cmd",
                r#"@set "_HANAMORI_CD_PREVIOUS=%CD%"
@cd %*
@if errorlevel 1 (set "_HANAMORI_CD_PREVIOUS=" & exit /b %errorlevel%)
@if "%_HANAMORI_CD_PREVIOUS%"=="%CD%" (set "_HANAMORI_CD_PREVIOUS=" & exit /b 0)
@set "_HANAMORI_CD_PREVIOUS="
@call "%~dp0hanamori.cmd" use --automatic
@exit /b 0
"#
                .replace('\n', "\r\n")
                .into_bytes(),
            ));
        }
        let mut digest = Sha256::new();
        for (name, bytes) in &files {
            digest.update(name.as_bytes());
            digest.update((bytes.len() as u64).to_le_bytes());
            digest.update(bytes);
        }
        let directory = base.join(format!("{:x}", digest.finalize()));
        Ok(Self {
            base: base.to_owned(),
            directory,
            files,
        })
    }

    pub fn directory(&self) -> &Path {
        &self.directory
    }

    pub fn loader_path(&self) -> PathBuf {
        self.directory.join("init.cmd")
    }

    /// No writes, including for an absent tree. Only known, byte-identical files may
    /// be reused; partial publication resumes by adding missing files, never replacing.
    pub fn complete(&self) -> Result<bool> {
        if !ordinary(&self.base, true)? || !ordinary(&self.directory, true)? {
            return Ok(false);
        }
        for entry in fs::read_dir(&self.directory)? {
            let entry = entry?;
            ensure!(
                self.files
                    .iter()
                    .any(|(name, _)| entry.file_name() == *name),
                "CMD loader directory contains unknown content; it was preserved: {}",
                self.directory.display()
            );
        }
        let mut complete = true;
        for (name, bytes) in &self.files {
            let path = self.directory.join(name);
            if ordinary(&path, false)? {
                ensure!(
                    fs::read(&path)? == *bytes,
                    "CMD loader file was modified; it was preserved: {}",
                    path.display()
                );
            } else {
                complete = false;
            }
        }
        Ok(complete)
    }

    pub fn publish(&self) -> Result<()> {
        self.complete()?;
        fs::create_dir_all(&self.base).context("cannot create CMD loader storage")?;
        ordinary(&self.base, true)?;
        let lock = self.base.join("hanamori-cmd-init.lock");
        ordinary(&lock, false)?;
        let _guard = FileLock::acquire(&lock)?;
        if self.complete()? {
            return Ok(());
        }
        match fs::create_dir(&self.directory) {
            Ok(()) => (),
            Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => (),
            Err(error) => return Err(error).context("cannot create CMD loader bundle"),
        }
        ordinary(&self.directory, true)?;
        self.complete()?;
        for (name, bytes) in &self.files {
            let path = self.directory.join(name);
            if ordinary(&path, false)? {
                ensure!(
                    fs::read(&path)? == *bytes,
                    "CMD loader changed during publication"
                );
                continue;
            }
            // Temporary files stay outside the immutable bundle, so a crash cannot
            // leave an unknown temporary file blocking a subsequent retry.
            let mut temporary = tempfile::Builder::new()
                .prefix("hanamori-cmd-write-")
                .tempfile_in(&self.base)?;
            temporary.write_all(bytes)?;
            temporary.as_file().sync_all()?;
            temporary
                .persist_noclobber(&path)
                .map_err(|error| error.error)
                .context("cannot publish CMD loader file without overwriting existing content")?;
        }
        ensure!(self.complete()?, "CMD loader publication is incomplete");
        Ok(())
    }
}

#[cfg(windows)]
pub struct InitReport {
    pub loader: PathBuf,
    pub entry: PathBuf,
    /// Published loader files, for the caller's startup records.
    pub files: Vec<(std::ffi::OsString, Vec<u8>)>,
    pub changed: bool,
}

#[cfg(windows)]
pub fn initialize(
    program: &Path,
    directory: Option<&DirectoryTarget>,
    auto_activate: bool,
    use_on_cd: bool,
    dry_run: bool,
) -> Result<InitReport> {
    use crate::shell::cmd::autorun::windows::UserPlan;
    let base = dirs::data_local_dir()
        .context("cannot locate the user local application data directory")?
        .join(crate::identity::PRODUCT_NAME)
        .join("shell")
        .join("cmd");
    let bundle = Bundle::new(&base, program, directory, auto_activate, use_on_cd)?;
    let loader = bundle.loader_path();
    let plan = UserPlan::new(Some(
        loader.to_str().context("CMD loader path must be Unicode")?,
    ))?;
    let changed = !bundle.complete()? || plan.plan().changed();
    publish_and_apply(&bundle, &plan, dry_run)?;
    Ok(InitReport {
        loader,
        entry: bundle.directory().join("hanamori.cmd"),
        files: bundle
            .files
            .iter()
            .map(|(name, bytes)| (bundle.directory.join(name).into_os_string(), bytes.clone()))
            .collect(),
        changed,
    })
}

#[cfg(windows)]
fn publish_and_apply(
    bundle: &Bundle,
    plan: &crate::shell::cmd::autorun::windows::UserPlan,
    dry_run: bool,
) -> Result<()> {
    bundle.complete()?;
    if !dry_run {
        bundle.publish()?;
        plan.apply().with_context(|| format!("CMD loader files were retained at {}; registry initialization did not complete; inspect and retry", bundle.directory().display()))?;
    }
    Ok(())
}

#[cfg(windows)]
pub fn deinitialize(dry_run: bool) -> Result<bool> {
    let plan = crate::shell::cmd::autorun::windows::UserPlan::new(None)?;
    let changed = plan.plan().changed();
    if !dry_run {
        plan.apply()?;
    }
    Ok(changed)
}

