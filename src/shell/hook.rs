//! Temporary shell wrappers. Rust owns argument parsing; shells only capture/apply
//! successfully generated scripts and invoke the pinned executable.

use crate::shell::quote::{posix_literal, powershell_literal};
use crate::shell::syntax::Shell;
use crate::shell::target::DirectoryTarget;
use anyhow::{ensure, Context, Result};
use base64::{engine::general_purpose::STANDARD, Engine};
use std::ffi::OsString;
use std::path::Path;

pub fn decode_arguments(value: &str) -> Result<Vec<OsString>> {
    let decoded = STANDARD
        .decode(value)
        .context("invalid encoded argument array")?;
    let arguments: Vec<String> =
        serde_json::from_slice(&decoded).context("invalid encoded argument structure")?;
    ensure!(
        arguments.iter().all(|value| !value.contains('\0')),
        "command arguments cannot contain NUL"
    );
    Ok(arguments.into_iter().map(OsString::from).collect())
}

/// Ordinary commands run outside command substitution, retaining terminal I/O and status.
pub fn forward_script(program: &Path, arguments: &[OsString], shell: Shell) -> Result<String> {
    let native_program = crate::paths::native(program);
    let program = native_program.as_path();
    match shell {
        Shell::Bash | Shell::Zsh => {
            let program = posix_executable(program)?;
            let mut words = vec!["command".to_owned(), "\"$_hanamori_executable\"".to_owned()];
            words.extend(
                arguments
                    .iter()
                    .map(|value| posix_literal(value))
                    .collect::<Result<Vec<_>>>()?,
            );
            let command = words.join(" ");
            // A subshell keeps this temporary variable out of the caller's environment.
            Ok(format!("( _hanamori_executable={program} && {command} )\n"))
        }
        Shell::PowerShell => {
            // Native argument reconstruction in Windows PowerShell can lose quotes and
            // empty strings. Pass one ASCII payload to a Rust argv launcher instead.
            let arguments = arguments
                .iter()
                .map(|value| {
                    value
                        .to_str()
                        .context("PowerShell cannot represent a non-Unicode command argument")
                })
                .collect::<Result<Vec<_>>>()?;
            let encoded = STANDARD.encode(serde_json::to_vec(&arguments)?);
            let command = format!(
                "& {} shell run --encoded-args {}",
                powershell_literal(
                    program
                        .to_str()
                        .context("PowerShell executable path must be Unicode")?
                ),
                powershell_literal(&encoded)
            );
            Ok(format!("if ($_hanamori_has_input) {{ $_hanamori_input | {command} }} else {{ {command} }}\n"))
        }
        Shell::Cmd => anyhow::bail!(
            "CMD forwards arguments through its batch entry; generate it with hanamori env --shell cmd --output hanamori.cmd"
        ),
    }
}

pub fn generate(
    program: &Path,
    directory: Option<&DirectoryTarget>,
    shell: Shell,
    auto_activate: bool,
    use_on_cd: bool,
) -> Result<String> {
    let native_program = crate::paths::native(program);
    let program = native_program.as_path();
    if shell == Shell::Cmd {
        ensure!(!use_on_cd, "CMD directory switching requires persistent initialization: hanamori shell init --shell cmd --use-on-cd");
        return crate::shell::cmd::hook::generate(program, directory, auto_activate);
    }
    ensure!(
        program.is_absolute(),
        "hook executable path must be absolute"
    );
    let arguments = directory
        .map(DirectoryTarget::arguments)
        .unwrap_or_default();
    let options = match shell {
        Shell::Bash | Shell::Zsh => arguments
            .iter()
            .map(|value| posix_literal(value))
            .collect::<Result<Vec<_>>>()?
            .join(" "),
        Shell::PowerShell => arguments
            .iter()
            .map(|value| {
                value
                    .to_str()
                    .context("PowerShell directory arguments must be Unicode")
                    .map(powershell_literal)
            })
            .collect::<Result<Vec<_>>>()?
            .join(" "),
        Shell::Cmd => unreachable!(),
    };
    let mut script =
        String::from("# Generated by Hanamori. Source this hook in the current shell.\n");
    match shell {
        Shell::Bash | Shell::Zsh => {
            // Bash 5.2 mishandles `builtin eval` failures in functions under
            // errexit. Zsh's `command` only searches external commands, so keep
            // its builtin dispatch. Both bypass a user function named eval.
            let eval_prefix = if matches!(shell, Shell::Bash) {
                "command"
            } else {
                "builtin"
            };
            let direct = if directory.is_none() {
                "    case \"${1-}\" in\n        use|deactivate|-*|'') ;;\n        *) command \"$_hanamori_executable\" \"$@\"; return $? ;;\n    esac\n".to_owned()
            } else {
                String::new()
            };
            script.push_str(&format!(r#"builtin unalias hanamori 2>/dev/null || :
hanamori() {{
    builtin local _hanamori_executable
    _hanamori_executable={program} || return $?
{direct}    builtin local _hanamori_script _hanamori_result
    if _hanamori_script=$(command "$_hanamori_executable" shell dispatch --shell {shell} {options} -- "$@"); then
        {eval_prefix} eval "$_hanamori_script"
    else
        _hanamori_result=$?
        return "$_hanamori_result"
    fi
}}
"#, program=posix_executable(program)?, shell=shell.name()));
            if auto_activate && !use_on_cd {
                script.push_str("if [ -z \"${_HANAMORI_STATE+x}\" ]; then\n    if ! hanamori use; then builtin printf '%s\\n' 'Hanamori: automatic activation failed; the shell remains available.' >&2; fi\nfi\n:\n");
            }
        }
        Shell::PowerShell => {
            script.push_str(&format!(r#"if (Test-Path -LiteralPath Alias:hanamori) {{ Remove-Item -LiteralPath Alias:hanamori -Force -ErrorAction Stop }}
function global:hanamori {{
    $_hanamori_has_input = $MyInvocation.ExpectingInput
    if ($_hanamori_has_input) {{ $_hanamori_input = $input }}
    $_hanamori_arguments = [string[]]$args
    $_hanamori_encoded = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes((ConvertTo-Json -InputObject $_hanamori_arguments -Compress)))
    $_hanamori_encoding = [Console]::OutputEncoding
    $_hanamori_result = 0
    try {{
        $global:LASTEXITCODE = 0
        [Console]::OutputEncoding = [Text.UTF8Encoding]::new($false)
        $_hanamori_script = & {program} shell dispatch --shell powershell {options} --encoded-args $_hanamori_encoded
        $_hanamori_result = $LASTEXITCODE
        if ($_hanamori_result -eq 0) {{
            . ([scriptblock]::Create(($_hanamori_script -join [Environment]::NewLine)))
            $_hanamori_result = $LASTEXITCODE
        }}
    }} catch {{
        if ($LASTEXITCODE -ne 0) {{ $_hanamori_result = $LASTEXITCODE }}
        else {{
            $_hanamori_result = 1
            [Console]::Error.WriteLine('Hanamori: command or environment update failed.')
        }}
    }} finally {{
        [Console]::OutputEncoding = $_hanamori_encoding
        $global:LASTEXITCODE = $_hanamori_result
    }}
}}
"#, program=powershell_literal(program.to_str().context("PowerShell executable path must be Unicode")?)));
            if auto_activate && !use_on_cd {
                script.push_str("if (!(Test-Path -LiteralPath Env:_HANAMORI_STATE)) {\n    hanamori use\n    if ($LASTEXITCODE -ne 0) { [Console]::Error.WriteLine('Hanamori: automatic activation failed; the shell remains available.') }\n    $global:LASTEXITCODE = 0\n}\n");
            }
        }
        Shell::Cmd => unreachable!("CMD batch entry generated above"),
    }
    script.push_str(&crate::shell::auto_switch::registration(shell, use_on_cd));
    Ok(script)
}

pub fn posix_executable(program: &Path) -> Result<String> {
    let native_program = crate::paths::native(program);
    let program = native_program.as_path();
    let quoted = posix_literal(program.as_os_str())?;
    // Native Windows paths must be translated by the shell's own MSYS runtime.
    if cfg!(windows) {
        Ok(format!("\"$(command cygpath -u -- {quoted})\""))
    } else {
        Ok(quoted)
    }
}

/// A persistent profile stores this small loader, not a toolchain environment snapshot.
pub fn loader(
    program: &Path,
    directory: Option<&DirectoryTarget>,
    shell: Shell,
    auto_activate: bool,
    completions: bool,
    use_on_cd: bool,
) -> Result<String> {
    let native_program = crate::paths::native(program);
    let program = native_program.as_path();
    ensure!(
        program.is_absolute(),
        "initialization executable path must be absolute"
    );
    let mut arguments: Vec<OsString> = vec!["env".into(), "--shell".into(), shell.name().into()];
    if let Some(directory) = directory {
        arguments.extend(directory.arguments());
    }
    if auto_activate {
        arguments.push("--auto-activate".into());
    }
    if completions {
        arguments.push("--completions".into());
    }
    if use_on_cd {
        arguments.push("--use-on-cd".into());
    }
    match shell {
        Shell::Bash | Shell::Zsh => {
            let command = forward_script(program, &arguments, shell)?;
            let eval_prefix = if matches!(shell, Shell::Bash) {
                "command"
            } else {
                "builtin"
            };
            Ok(format!(
                r#"_hanamori_initialize() {{
    builtin local _hanamori_hook
    if _hanamori_hook=$( {command}); then
        if ! {eval_prefix} eval "$_hanamori_hook"; then
            builtin printf '%s\n' 'Hanamori: hook loading failed; regenerate shell initialization.' >&2
        fi
    else
        builtin printf '%s\n' 'Hanamori: executable unavailable or hook generation failed; regenerate shell initialization.' >&2
    fi
}}
_hanamori_initialize
builtin unset -f _hanamori_initialize
"#,
                command = command.trim_end()
            ))
        }
        Shell::PowerShell => {
            let arguments = arguments
                .iter()
                .map(|value| {
                    value
                        .to_str()
                        .context("PowerShell initialization paths must be Unicode")
                })
                .collect::<Result<Vec<_>>>()?;
            let encoded = STANDARD.encode(serde_json::to_vec(&arguments)?);
            // Encoding the executable also keeps CRLF normalization outside path literals.
            let executable = STANDARD.encode(
                program
                    .to_str()
                    .context("PowerShell executable path must be Unicode")?
                    .as_bytes(),
            );
            Ok(format!(
                r#"& {{
    $_hanamori_encoding = [Console]::OutputEncoding
    try {{
        [Console]::OutputEncoding = [Text.UTF8Encoding]::new($false)
        $_hanamori_hook = & ([Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('{executable}'))) shell run --encoded-args '{encoded}'
        if ($LASTEXITCODE -ne 0) {{ throw 'Hook generation failed' }}
        . ([scriptblock]::Create(($_hanamori_hook -join [Environment]::NewLine)))
    }} catch {{
        [Console]::Error.WriteLine('Hanamori: executable unavailable or hook loading failed; regenerate shell initialization.')
    }} finally {{
        [Console]::OutputEncoding = $_hanamori_encoding
        $global:LASTEXITCODE = 0
    }}
}}
"#
            ))
        }
        Shell::Cmd => {
            anyhow::bail!("CMD uses a batch entry and AutoRun, not a startup profile file")
        }
    }
}
