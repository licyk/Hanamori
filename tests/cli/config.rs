use hanamori_test_support::toolchain as common;
use serde_json::Value;
use std::process::Command;

fn command(temp: &tempfile::TempDir) -> Command {
    let mut command = Command::new(env!("CARGO_BIN_EXE_hanamori"));
    command.env_clear().current_dir(temp.path());
    command
        .arg("--manager-dir")
        .arg(temp.path().join("manager"));
    command
}

#[test]
fn config_command_preserves_explicitness_and_writes_only_json_to_stdout() {
    let temp = tempfile::tempdir().unwrap();
    let output = command(&temp)
        .env("HANAMORI_FILE_WORKERS", "7")
        .env("HANAMORI_CONNECTIONS", "6")
        .env("RUST_LOG", "not-a-filter!")
        .args([
            "--connections",
            "3",
            "config",
            "show",
            "--resolved",
            "--json",
            "--log",
            "warn",
        ])
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(output.stderr.is_empty());
    let config: Value = serde_json::from_slice(&output.stdout).unwrap();
    assert_eq!(config["file_workers"]["value"], 7);
    assert_eq!(config["file_workers"]["source"], "environment");
    assert_eq!(config["connections"]["value"], 3);
    assert_eq!(config["connections"]["source"], "cli");
    assert_eq!(config["log"]["value"], "warn");
    assert!(!temp.path().join("manager").exists());
}

#[test]
fn invalid_installation_options_fail_before_touching_disk_or_network() {
    let temp = tempfile::tempdir().unwrap();
    for args in [
        vec!["--arch", "arm64/arm64"],
        vec!["--profile", "full"],
        vec!["--profile", "compiler-only", "--sdk", "26100"],
        vec!["--profile", "compiler-only", "--sdk", "latest"],
        vec!["--file-workers", "0"],
        vec!["--connections", "65"],
    ] {
        let output = command(&temp)
            .args([
                "install",
                "--dir",
                "tools",
                "--download-dir",
                "downloads",
                "--manifest",
                "http://127.0.0.1:1",
            ])
            .args(args)
            .output()
            .unwrap();
        assert!(!output.status.success());
        assert!(!String::from_utf8_lossy(&output.stderr).contains("cannot fetch"));
        assert!(!temp.path().join("tools").exists());
        assert!(!temp.path().join("downloads").exists());
        assert!(!temp.path().join("manager").exists());
    }
}

#[test]
fn invalid_proxy_and_mirror_errors_include_the_input() {
    let temp = tempfile::tempdir().unwrap();
    // Environment input deliberately avoids clap's own command-line type diagnostics.
    for field in ["HANAMORI_PROXY", "HANAMORI_MIRROR"] {
        let output = command(&temp)
            .env(field, "file:///very-secret-token")
            .args(["config", "show", "--resolved"])
            .output()
            .unwrap();
        assert!(!output.status.success());
        assert!(output.stdout.is_empty());
        assert!(String::from_utf8_lossy(&output.stderr).contains("file:///very-secret-token"));
    }
}

#[test]
fn environment_export_ignores_irrelevant_network_config_and_rust_log() {
    let temp = tempfile::tempdir().unwrap();
    let root = temp.path().join("tools");
    common::toolchain(&root, "14.44.35207", None);
    let output = command(&temp)
        .env("HANAMORI_PROXY", "invalid")
        .env("HANAMORI_CONNECTIONS", "invalid")
        .env("RUST_LOG", "trace")
        .args([
            "shell",
            "activate",
            "--dir",
            "tools",
            "--shell",
            "powershell",
        ])
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(output.stderr.is_empty());
    let script = String::from_utf8(output.stdout).unwrap();
    assert!(script.starts_with("# Generated by Hanamori;"));
    assert!(script.contains("'VCToolsVersion' = '14.44.35207'"));
    assert!(!temp.path().join("manager").exists());
}

#[test]
fn optional_schema_and_unknown_config_fields_do_not_block_local_commands() {
    let temp = tempfile::tempdir().unwrap();
    let home = temp.path().join("manager");
    std::fs::create_dir(&home).unwrap();
    for content in [
        "{}",
        r#"{"schema_version":1,"comment":"notes","manager_dir":"ignored"}"#,
    ] {
        std::fs::write(home.join("config.json"), content).unwrap();
        let output = command(&temp).arg("list").output().unwrap();
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        assert!(!temp.path().join("ignored").exists());
    }
}

#[test]
fn doctor_reports_broken_configuration_without_changing_tools() {
    let temp = tempfile::tempdir().unwrap();
    let home = temp.path().join("manager");
    std::fs::create_dir(&home).unwrap();
    let root = temp.path().join("tools");
    common::toolchain(&root, "14.44.35207", None);
    let imported = command(&temp)
        .args(["import", "--name", "tools", "--dir"])
        .arg(&root)
        .output()
        .unwrap();
    assert!(
        imported.status.success(),
        "{}",
        String::from_utf8_lossy(&imported.stderr)
    );
    for content in ["{broken", r#"{"log":"invalid["}"#] {
        std::fs::write(home.join("config.json"), content).unwrap();
        let output = command(&temp).args(["doctor", "--json"]).output().unwrap();
        assert!(!output.status.success());
        let report: Value = serde_json::from_slice(&output.stdout).unwrap();
        assert_eq!(report["healthy"], false);
        assert!(report["issues"]
            .as_array()
            .unwrap()
            .iter()
            .any(|issue| issue.as_str().unwrap().contains("config_invalid")));
    }
}

#[test]
fn config_show_defaults_to_values_and_resolved_adds_origins() {
    let temp = tempfile::tempdir().unwrap();
    let output = command(&temp)
        .args(["config", "show", "--json"])
        .output()
        .unwrap();
    assert!(output.status.success());
    let values: Value = serde_json::from_slice(&output.stdout).unwrap();
    assert_eq!(values["file_workers"], 4);
    assert_eq!(values["connections"], 8);
    assert_eq!(values["log"], "info");
    assert!(values["manager_dir"].is_string());
    for resolved in [false, true] {
        let mut child = command(&temp);
        child.args(["--log", "off", "config", "show"]);
        if resolved {
            child.arg("--resolved");
        }
        let output = child.output().unwrap();
        assert!(output.status.success(), "{output:?}");
        assert!(output.stderr.is_empty());
        let text = String::from_utf8(output.stdout).unwrap();
        assert!(text.contains("Setting") && text.contains("Value"), "{text}");
        assert_eq!(text.contains("Source"), resolved, "{text}");
        assert!(
            text.lines()
                .any(|line| line.split_whitespace().take(2).eq(["file_workers", "4"])),
            "{text}"
        );
        assert!(text.contains(temp.path().to_str().unwrap()), "{text}");
        if resolved {
            assert!(text.contains("manager_dir: cli"), "{text}");
        }
    }
    assert!(!temp.path().join("manager").exists());
}
